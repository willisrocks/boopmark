def concept_of():
    """raw tag -> concept id; raises if a raw tag is listed twice."""
    out = {}
    for concept, raws in CONCEPTS.items():
        for raw in raws:
            if raw in out:
                raise ValueError(f"duplicate raw tag {raw!r} in {concept} and {out[raw]}")
            out[raw] = concept
    return out
